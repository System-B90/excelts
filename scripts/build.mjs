/*
 * Name: build.mjs
 * Purpose: Builds @system-b90/excelts -- the library in src/ and its whole
 *          dependency tree -- as one self-contained, zero-dependency bundle.
 * Created: 2026-10-23
 * Author: Michael K. Steinberg
 *
 * Usage: npm ci && npm run build
 *
 * Outputs, all under dist/:
 *   index.cjs                the bundle: module.exports = the public API
 *   index.mjs                ESM entry over the bundle, with named exports
 *   types.d.ts               the API's declarations, from src/types.d.ts
 *   index.d.cts / index.d.mts  per-format entry declarations over types.d.ts
 *   THIRD_PARTY_NOTICES.md   licence text of every package inside the bundle
 *   provenance.json          what the bundle was built from
 */

import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { build, version as esbuildVersion } from "esbuild";

import { applyPatches, PATCHES, patchesFor } from "./patches.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");
const require = createRequire(join(ROOT, "package.json"));

/**
 * Modules dependencies require at load time, but only on code paths this
 * library never takes. Stubbed out of the bundle -- see
 * src/shims/unreachable.cjs for each one and why.
 */
const UNREACHABLE = [ "buffers", "chainsaw", "fstream", "glob", "readdir-glob" ];

/** Patch ids actually applied, so a patch whose module stopped loading fails the build. */
const applied = new Set();

const shims = {
    name: "excelts-shims",
    setup(b) {
        // Bug fixes in bundled dependencies; see scripts/patches.mjs.
        const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replaceAll("/", "[\\\\/]");
        const patched = new RegExp(`[\\\\/]node_modules[\\\\/](${PATCHES.map((p) => escape(p.module)).join("|")})$`);
        b.onLoad({ filter: patched }, (args) => {
            const contents = applyPatches(args.path, readFileSync(args.path, "utf8"));
            for (const p of patchesFor(args.path)) applied.add(p.id);
            return { contents, loader: "js" };
        });

        const unreachable = new RegExp(`^(${UNREACHABLE.join("|")})$`);
        b.onResolve({ filter: unreachable }, (args) => ({ path: args.path, namespace: "unreachable" }));
        b.onLoad({ filter: /.*/, namespace: "unreachable" }, (args) => ({
            contents: `module.exports = require(${JSON.stringify(join(ROOT, "src", "shims", "unreachable.cjs"))})(${JSON.stringify(args.path)});`,
            resolveDir: ROOT,
            loader: "js",
        }));
    },
};

/**
 * Licences a bundled package may carry. Anything else fails the build, so a
 * dependency bump cannot quietly ship copyleft code under this package's MIT.
 * jszip's dual licence is taken under MIT.
 */
const ALLOWED_LICENSES = new Set([
    "MIT",
    "ISC",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "Apache-2.0",
    "0BSD",
    "Unlicense",
    "Zlib",
    "(MIT AND Zlib)",
    "(MIT OR GPL-3.0-or-later)",
    "(MIT OR Apache-2.0)",
]);

rmSync(DIST, { recursive: true, force: true });
mkdirSync(DIST);

const result = await build({
    entryPoints: [ join(ROOT, "src", "index.cjs") ],
    // Module keys inside the bundle are paths relative to this; pinning it
    // keeps the output byte-identical whichever directory runs the build.
    absWorkingDir: ROOT,
    bundle: true,
    format: "cjs",
    platform: "node",
    // Matches `engines.node`; the syntax floor, not the runtime the tests use.
    target: "node20",
    minify: true,
    // Not optional: src/lib/doc/worksheet.js tests `constructor.name ===
    // "MergeValue"` when insertRows re-merges cells, and minified class names
    // break it.
    keepNames: true,
    // Licences ship in full in THIRD_PARTY_NOTICES.md instead.
    legalComments: "none",
    metafile: true,
    plugins: [ shims ],
    outfile: join(DIST, "index.cjs"),
});

const unapplied = PATCHES.filter((p) => !applied.has(p.id)).map((p) => p.id);
if (unapplied.length > 0) {
    throw new Error(`Patches never applied (their module is no longer bundled?): ${unapplied.join(", ")}`);
}

// ── ESM entry ────────────────────────────────────────────────────────────────
// Generated from the bundle's real export object, so the named exports cannot
// drift from what `require` returns. `import excelts from "./index.cjs"` is
// plain ESM-over-CJS interop: no `require` shim for Next.js to choke on.
const bundled = require(join(DIST, "index.cjs"));
const names = Object.keys(bundled).sort();
writeFileSync(
    join(DIST, "index.mjs"),
    [
        "// Generated by scripts/build.mjs: the ESM entry over the CommonJS bundle.",
        'import excelts from "./index.cjs";',
        "",
        `export const { ${names.join(", ")} } = excelts;`,
        "export default excelts;",
        "",
    ].join("\n"),
);

// ── Types ────────────────────────────────────────────────────────────────────
// One self-contained declaration file with no imports, shared by both entries.
copyFileSync(join(ROOT, "src", "types.d.ts"), join(DIST, "types.d.ts"));
const typesHeader = "// Generated by scripts/build.mjs. The API's declarations are in types.d.ts.";
writeFileSync(join(DIST, "index.d.cts"), [ typesHeader, 'export * from "./types.js";', "" ].join("\n"));
writeFileSync(
    join(DIST, "index.d.mts"),
    [
        typesHeader,
        'import * as excelts from "./types.js";',
        'export * from "./types.js";',
        "export default excelts;",
        "",
    ].join("\n"),
);

// ── Third-party notices ──────────────────────────────────────────────────────
// `legalComments: "none"` keeps the bundle lean, and most packages carry no
// licence header anyway. MIT and friends still require the notice to travel
// with every copy, so the full licence of each bundled package ships here.

/** Maps a bundled input path to the directory of the package that owns it. */
function packageDirOf(input) {
    const parts = input.split(/[\\/]/);
    const at = parts.lastIndexOf("node_modules");
    if (at === -1) return null;
    const take = parts[at + 1].startsWith("@") ? 3 : 2;
    return join(ROOT, ...parts.slice(0, at + take));
}

/** The package's licence file, plus its NOTICE file when it has one (Apache-2.0 asks for both). */
function licenseTextOf(dir) {
    const files = readdirSync(dir);
    const read = (pattern) => {
        const file = files.find((f) => pattern.test(f));
        return file ? readFileSync(join(dir, file), "utf8").trim() : null;
    };
    const texts = [ read(/^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i), read(/^notice(\.(md|txt))?$/i) ];
    return texts.filter(Boolean).join("\n\n") || null;
}

// Keyed by name@version: the tree nests several identical copies of some
// packages (isarray, readable-stream), and each needs its notice only once.
const packages = new Map();
const seenDirs = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
    const dir = packageDirOf(input);
    if (!dir || seenDirs.has(dir)) continue;
    seenDirs.add(dir);
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    if (packages.has(`${pkg.name}@${pkg.version}`)) continue;
    const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type;
    if (!ALLOWED_LICENSES.has(license)) {
        throw new Error(
            `Refusing to build: ${pkg.name}@${pkg.version} is licensed "${license}", which is not in ` +
                "ALLOWED_LICENSES. Review it before adding it there.",
        );
    }
    const author = typeof pkg.author === "string" ? pkg.author : pkg.author?.name;
    packages.set(`${pkg.name}@${pkg.version}`, {
        name: pkg.name,
        version: pkg.version,
        license,
        author,
        text: licenseTextOf(dir),
    });
}

const bundledPackages = [ ...packages.values() ].sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
);

writeFileSync(
    join(DIST, "THIRD_PARTY_NOTICES.md"),
    [
        "# Third-party notices",
        "",
        `\`dist/index.cjs\` bundles the following ${bundledPackages.length} packages. Each is redistributed`,
        "under the licence reproduced below.",
        "",
        ...bundledPackages.flatMap(({ name, version, license, author, text }) => [
            `## ${name}@${version}`,
            "",
            `License: ${license}`,
            ...(author ? [ `Author: ${author}` ] : []),
            "",
            ...(text
                ? [ "```text", text, "```" ]
                : [ `This package ships no licence file; it declares "${license}" in its package.json.` ]),
            "",
        ]),
    ].join("\n"),
);

// ── Provenance ───────────────────────────────────────────────────────────────
const bundle = readFileSync(join(DIST, "index.cjs"));
const provenance = {
    esbuild: esbuildVersion,
    bundleBytes: bundle.length,
    bundleSha256: createHash("sha256").update(bundle).digest("hex"),
    exports: names,
    unreachable: UNREACHABLE,
    patches: PATCHES.map(({ id, module }) => ({ id, module })),
    bundledPackages: bundledPackages.map(({ name, version, license }) => ({ name, version, license })),
};
writeFileSync(join(DIST, "provenance.json"), `${JSON.stringify(provenance, null, 4)}\n`);

for (const file of [ "index.cjs", "index.mjs", "types.d.ts", "index.d.cts", "index.d.mts" ]) {
    if (!existsSync(join(DIST, file))) throw new Error(`Build did not produce dist/${file}`);
}

console.log(
    `Bundled src/ + ${bundledPackages.length} dependencies -> ` +
        `${(bundle.length / 1024).toFixed(0)}KB, ${names.length} exports`,
);
